import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Reuse the frontend toolchain; this bundles source without starting a server.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const frontendRequire = createRequire(
    path.join(root, 'packages/frontend/package.json'),
);
const viteRequire = createRequire(frontendRequire.resolve('vite/package.json'));
const { build } = viteRequire('esbuild');
const fixtureDir = path.join(
    root,
    'packages/backend/src/database/seeds/development/fixtures/slow-data-app-viz',
);

await build({
    stdin: {
        contents: await readFile(
            path.join(fixtureDir, 'fixture.tsx.txt'),
            'utf8',
        ),
        sourcefile: 'slow-data-app-viz-fixture.tsx',
        resolveDir: root,
        loader: 'tsx',
    },
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: 'es2020',
    jsx: 'automatic',
    minify: true,
    define: {
        'process.env.NODE_ENV': '"production"',
        'import.meta.env': '{}',
    },
    alias: {
        '@lightdash/query-sdk': path.join(
            root,
            'packages/query-sdk/src/index.ts',
        ),
        react: path.join(root, 'packages/frontend/node_modules/react'),
        'react-dom': path.join(
            root,
            'packages/frontend/node_modules/react-dom',
        ),
    },
    banner: {
        js: '// Generated by node scripts/build-slow-data-app-viz-fixture.mjs. See fixture.tsx.txt.',
    },
    legalComments: 'inline',
    outfile: path.join(fixtureDir, 'fixture.js.txt'),
});
