/**
 * When each walkthrough was released: the day its entry first appeared in
 * generated.ts, read from git history. Nothing here is written by a person.
 *
 * The day is looked up once, the first time the generator meets a scope with
 * no recorded day, and then kept: released.ts is the record, so a shallow CI
 * checkout (no history) regenerates the same file. A scope whose entry has
 * never been committed (a walkthrough added on the branch being generated)
 * has no commit to read yet, so it gets the day it was first generated,
 * which is the day its author ran the generator for it. A scope that loses
 * its walkthrough loses its day, so one that comes back later is new again.
 *
 * The homepage's Learn block (Newest modules) sorts by this day.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { outputPath, root } from './lib';

export const releasedPath = path.join(path.dirname(outputPath), 'released.ts');

const DAY = /^\d{4}-\d{2}-\d{2}$/;

/** The days already recorded in released.ts, if it exists. */
export const readRecordedDays = (
    file: string = releasedPath,
): Record<string, string> => {
    if (!existsSync(file)) return {};
    const source = readFileSync(file, 'utf8');
    const days: Record<string, string> = {};
    for (const match of source.matchAll(
        /^\s*['"]([^'"]+)['"]:\s*['"](\d{4}-\d{2}-\d{2})['"],?$/gm,
    )) {
        days[match[1]] = match[2];
    }
    return days;
};

const escapeRegex = (value: string) =>
    value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * The committer day of the oldest commit that added the scope's entry to
 * generated.ts, or null when history has none (an uncommitted walkthrough,
 * or a checkout without history).
 */
export const dayFromGit = (scope: string): string | null => {
    const relative = path.relative(root, outputPath);
    try {
        const out = execFileSync(
            'git',
            [
                'log',
                '--format=%cs',
                // POSIX extended, so it means the same to every git build.
                '--extended-regexp',
                `-G^[[:space:]]*['"]${escapeRegex(scope)}['"]: [{]`,
                '--',
                relative,
            ],
            {
                cwd: root,
                encoding: 'utf8',
                stdio: ['ignore', 'pipe', 'ignore'],
            },
        )
            .trim()
            .split('\n')
            .filter((line) => DAY.test(line));
        return out.length > 0 ? out[out.length - 1] : null;
    } catch {
        return null;
    }
};

const today = () => new Date().toISOString().slice(0, 10);

/**
 * One day per scope, for exactly the scopes given: recorded days are kept,
 * missing ones are read from git, and failing that stamped with today.
 */
export const releaseDays = (
    scopes: string[],
    recorded: Record<string, string> = readRecordedDays(),
    lookup: (scope: string) => string | null = dayFromGit,
    now: () => string = today,
): Record<string, string> =>
    Object.fromEntries(
        [...scopes]
            .sort()
            .map((scope) => [scope, recorded[scope] ?? lookup(scope) ?? now()]),
    );

export const renderReleased = (days: Record<string, string>): string => {
    const body = Object.entries(days)
        .map(
            ([scope, day]) =>
                `    ${JSON.stringify(scope)}: ${JSON.stringify(day)},`,
        )
        .join('\n');
    return `/* eslint-disable */
// Generated by scripts/scope-tours/generate.ts (see released.ts there). Do not
// edit by hand; run \`pnpm scope-tours:generate\`.
//
// The day each walkthrough was released: when its entry first appeared in
// generated.ts, read once from git history and then kept. A walkthrough
// generated before its first commit carries the day it was first generated.

export const TOUR_RELEASED: Record<string, string> = ${body ? `{\n${body}\n}` : '{}'};
`;
};
