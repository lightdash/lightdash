import { execFileSync } from 'child_process';
import path from 'path';
import {
    LIGHTDASH_URL,
    lightdashApi,
    loginToLightdash,
    rootDir,
} from './dev-lightdash-api';

const DASHBOARD_NAME = process.env.ANALYTICS_DASHBOARD_NAME || 'Analytics';
const SPACE_NAME = 'SDK analytics example';
const CHART_TYPES_DIR = path.join(import.meta.dirname, 'analytics-chart-types');
const CLI_PATH = path.join(rootDir, 'packages/cli/dist/index.js');
const BUILD_TIMEOUT_MS = 10 * 60 * 1000;

type Project = { projectUuid: string; name: string };
type Space = { uuid: string; name: string };
type DashboardSummary = { uuid: string; name: string; spaceUuid: string };
type ChartType = { appUuid: string; slug: string };
type AppVersion = { version: number; status: string; error: string | null };
type UpdateEmbed = {
    dashboardUuids: string[];
    allowAllDashboards: boolean;
    chartUuids: string[];
    allowAllCharts: boolean;
};

const START_MONTH = 'subscriptions_subscription_start_month';
const PLAN = 'subscriptions_plan_name';
const STATUS = 'subscriptions_subscription_status';
const TOTAL = 'subscriptions_total_subscriptions';

type ChartSpec = {
    name: string;
    slug: string;
    dimensions: string[];
    metrics: string[];
    fieldMapping: Record<string, string | string[]>;
    optionValues: Record<string, string | number | boolean>;
};

const CHART_SPECS: ChartSpec[] = [
    {
        name: 'Cancellation rate',
        slug: 'rate-trend',
        dimensions: [START_MONTH, PLAN],
        metrics: ['subscriptions_cancelled_subscriptions', TOTAL],
        fieldMapping: {
            time: START_MONTH,
            numerator: 'subscriptions_cancelled_subscriptions',
            denominator: TOTAL,
            breakdowns: [PLAN],
        },
        optionValues: {
            subtitle:
                'Share of subscriptions started each month that were later cancelled.',
            target: 80,
            targetLabel: 'Target',
            useFieldColors: false,
        },
    },
    {
        name: 'New subscriptions',
        slug: 'breakdown-bars',
        dimensions: [START_MONTH, PLAN, STATUS],
        metrics: [TOTAL],
        fieldMapping: {
            time: START_MONTH,
            value: TOTAL,
            breakdowns: [PLAN, STATUS],
        },
        optionValues: {
            subtitle: 'Subscriptions started each month.',
            legendLabel: 'All plans',
            useFieldColors: false,
        },
    },
    {
        name: 'Monthly recurring revenue by plan',
        slug: 'composition-stack',
        dimensions: [START_MONTH, PLAN],
        metrics: ['subscriptions_total_monthly_mrr'],
        fieldMapping: {
            time: START_MONTH,
            component: PLAN,
            value: 'subscriptions_total_monthly_mrr',
        },
        optionValues: {
            subtitle: 'Where new recurring revenue comes from each month.',
            totalLabel: 'Total MRR added per month',
            useFieldColors: false,
        },
    },
];

async function findProject(cookie: string): Promise<Project> {
    const projects = await lightdashApi<Project[]>(
        cookie,
        'GET',
        '/api/v1/org/projects',
    );
    const projectUuid = process.env.PROJECT_UUID;
    const project = projectUuid
        ? projects.find((p) => p.projectUuid === projectUuid)
        : (projects.find((p) => p.name === 'Jaffle shop') ?? projects[0]);
    if (!project) throw new Error('No project found');
    return project;
}

async function ensureSpace(cookie: string, projectUuid: string) {
    const spaces = await lightdashApi<Space[]>(
        cookie,
        'GET',
        `/api/v1/projects/${projectUuid}/spaces`,
    );
    const existing = spaces.find((space) => space.name === SPACE_NAME);
    if (existing) return existing.uuid;
    const created = await lightdashApi<Space>(
        cookie,
        'POST',
        `/api/v1/projects/${projectUuid}/spaces`,
        { name: SPACE_NAME },
    );
    return created.uuid;
}

async function uploadChartTypes(cookie: string, projectUuid: string) {
    const { token } = await lightdashApi<{ token: string }>(
        cookie,
        'POST',
        '/api/v1/user/me/personal-access-tokens',
        {
            description: 'SDK test app analytics setup',
            expiresAt: new Date(Date.now() + 60 * 60 * 1000),
            autoGenerated: true,
        },
    );
    execFileSync(
        process.execPath,
        [
            CLI_PATH,
            'upload',
            '--chart-types-only',
            '--path',
            CHART_TYPES_DIR,
            '--project',
            projectUuid,
        ],
        {
            stdio: 'inherit',
            env: {
                ...process.env,
                LIGHTDASH_URL,
                LIGHTDASH_API_KEY: token,
            },
        },
    );
}

async function waitForChartTypes(
    cookie: string,
    projectUuid: string,
): Promise<Map<string, string>> {
    const slugs = CHART_SPECS.map((spec) => spec.slug);
    const deadline = Date.now() + BUILD_TIMEOUT_MS;
    while (Date.now() < deadline) {
        const chartTypes = await lightdashApi<ChartType[]>(
            cookie,
            'GET',
            `/api/v1/ee/projects/${projectUuid}/apps/chart-types`,
        );
        const statuses = await Promise.all(
            slugs.map(async (slug) => {
                const chartType = chartTypes.find((c) => c.slug === slug);
                if (!chartType) return { slug, appUuid: null, status: null };
                const app = await lightdashApi<{ versions: AppVersion[] }>(
                    cookie,
                    'GET',
                    `/api/v1/ee/projects/${projectUuid}/apps/${chartType.appUuid}`,
                );
                const [latest] = app.versions;
                if (latest?.status === 'error') {
                    throw new Error(
                        `Chart type ${slug} failed to build: ${latest.error}`,
                    );
                }
                return {
                    slug,
                    appUuid: chartType.appUuid,
                    status: latest?.status ?? null,
                };
            }),
        );
        if (statuses.every((s) => s.status === 'ready' && s.appUuid)) {
            return new Map(statuses.map((s) => [s.slug, s.appUuid as string]));
        }
        console.log(
            `Waiting for chart type builds: ${statuses
                .map((s) => `${s.slug}=${s.status ?? 'missing'}`)
                .join(', ')}`,
        );
        await new Promise((resolve) => {
            setTimeout(resolve, 5000);
        });
    }
    throw new Error('Timed out waiting for chart type builds');
}

async function createChart(
    cookie: string,
    projectUuid: string,
    spaceUuid: string,
    spec: ChartSpec,
    dataAppVizUuid: string,
): Promise<string> {
    const chart = await lightdashApi<{ uuid: string }>(
        cookie,
        'POST',
        `/api/v1/projects/${projectUuid}/saved`,
        {
            name: spec.name,
            tableName: 'subscriptions',
            spaceUuid,
            metricQuery: {
                exploreName: 'subscriptions',
                dimensions: spec.dimensions,
                metrics: spec.metrics,
                filters: {},
                sorts: [{ fieldId: START_MONTH, descending: false }],
                limit: 5000,
                tableCalculations: [],
            },
            chartConfig: {
                type: 'data_app_viz',
                config: {
                    dataAppVizUuid,
                    fieldMapping: spec.fieldMapping,
                    optionValues: spec.optionValues,
                },
            },
            tableConfig: { columnOrder: [] },
        },
    );
    return chart.uuid;
}

async function ensureDashboard(
    cookie: string,
    projectUuid: string,
    spaceUuid: string,
    chartTypeUuids: Map<string, string>,
): Promise<string> {
    const dashboards = await lightdashApi<DashboardSummary[]>(
        cookie,
        'GET',
        `/api/v1/projects/${projectUuid}/dashboards`,
    );
    const existing = dashboards.find(
        (d) => d.name === DASHBOARD_NAME && d.spaceUuid === spaceUuid,
    );
    if (existing) {
        console.log(`Reusing dashboard "${DASHBOARD_NAME}" (${existing.uuid})`);
        return existing.uuid;
    }

    const [rateChart, barsChart, stackChart] = await Promise.all(
        CHART_SPECS.map((spec) => {
            const dataAppVizUuid = chartTypeUuids.get(spec.slug);
            if (!dataAppVizUuid) throw new Error(`Missing ${spec.slug}`);
            return createChart(
                cookie,
                projectUuid,
                spaceUuid,
                spec,
                dataAppVizUuid,
            );
        }),
    );
    const tile = (
        savedChartUuid: string,
        x: number,
        y: number,
        w: number,
        h: number,
    ) => ({
        type: 'saved_chart',
        x,
        y,
        w,
        h,
        tabUuid: null,
        properties: { savedChartUuid },
    });
    const dashboard = await lightdashApi<{ uuid: string }>(
        cookie,
        'POST',
        `/api/v1/projects/${projectUuid}/dashboards`,
        {
            name: DASHBOARD_NAME,
            spaceUuid,
            tabs: [],
            tiles: [
                tile(rateChart, 0, 0, 18, 8),
                tile(barsChart, 18, 0, 18, 8),
                tile(stackChart, 0, 8, 36, 9),
            ],
        },
    );
    console.log(`Created dashboard "${DASHBOARD_NAME}" (${dashboard.uuid})`);
    return dashboard.uuid;
}

async function ensureEmbeddable(
    cookie: string,
    projectUuid: string,
    dashboardUuid: string,
) {
    const configPath = `/api/v1/embed/${projectUuid}/config`;
    const embedConfig = await lightdashApi<UpdateEmbed>(
        cookie,
        'GET',
        configPath,
    ).catch(() => null);
    if (!embedConfig) {
        await lightdashApi(cookie, 'POST', configPath, {
            dashboardUuids: [dashboardUuid],
        });
        return;
    }
    if (
        embedConfig.allowAllDashboards ||
        embedConfig.dashboardUuids.includes(dashboardUuid)
    ) {
        return;
    }
    await lightdashApi(cookie, 'PATCH', `${configPath}/dashboards`, {
        dashboardUuids: [...embedConfig.dashboardUuids, dashboardUuid],
        allowAllDashboards: false,
        chartUuids: embedConfig.chartUuids,
        allowAllCharts: embedConfig.allowAllCharts,
    });
}

async function main() {
    const cookie = await loginToLightdash();
    const { projectUuid, name } = await findProject(cookie);
    console.log(`Using project "${name}" (${projectUuid})`);

    await uploadChartTypes(cookie, projectUuid);
    const chartTypeUuids = await waitForChartTypes(cookie, projectUuid);
    const spaceUuid = await ensureSpace(cookie, projectUuid);
    const dashboardUuid = await ensureDashboard(
        cookie,
        projectUuid,
        spaceUuid,
        chartTypeUuids,
    );
    await ensureEmbeddable(cookie, projectUuid, dashboardUuid);

    const { url } = await lightdashApi<{ url: string }>(
        cookie,
        'POST',
        `/api/v1/embed/${projectUuid}/get-embed-url`,
        {
            content: {
                type: 'dashboard',
                projectUuid,
                dashboardUuid,
                dashboardFiltersInteractivity: { enabled: 'all', hidden: true },
                canExplore: true,
                canExportCsv: true,
                canViewUnderlyingData: true,
                canExportPagePdf: false,
            },
            user: { email: 'demo@lightdash.com' },
            expiresIn: '24h',
        },
    );

    console.log(`\nAdd to packages/sdk-test-app/.env.local:`);
    console.log(`VITE_ANALYTICS_EMBED_URL="${url}"`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
