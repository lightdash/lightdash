import { formatTimestamp } from '@lightdash/common';
import { Button, Select, Stack, TextInput } from '@mantine/core';
import { useForm } from '@mantine/form';
import { IconKey } from '@tabler/icons-react';
import { type FC } from 'react';
import { useTranslation } from 'react-i18next';
import useHealth from '../../../hooks/health/useHealth';
import { useCreateAccessToken } from '../../../hooks/useAccessToken';
import Callout from '../../common/Callout';
import { CopyActionIcon } from '../../common/CopyActionIcon';
import MantineModal from '../../common/MantineModal';
import { useExpireOptions } from './useExpireOptions';

export const CreateTokenModal: FC<{
    onBackClick: () => void;
}> = ({ onBackClick }) => {
    const { t } = useTranslation('userSettings');
    const health = useHealth();

    const {
        data,
        mutate: createAccessToken,
        isLoading,
        isSuccess,
    } = useCreateAccessToken();

    const expireOptions = useExpireOptions(true);

    const form = useForm({
        initialValues: {
            description: '',
            expiresAt: expireOptions[0].value,
        },
    });

    const handleOnSubmit = form.onSubmit(({ description, expiresAt }) => {
        const currentDate = new Date();
        const dateWhenExpires = !!Number(expiresAt)
            ? new Date(
                  currentDate.setDate(
                      currentDate.getDate() + Number(expiresAt),
                  ),
              )
            : undefined;

        createAccessToken({
            description,
            expiresAt: dateWhenExpires ?? null,
            autoGenerated: false,
        });
    });

    return (
        <MantineModal
            opened
            onClose={onBackClick}
            role="alertdialog"
            title={
                data
                    ? t('accessTokensPanel.createTokenModal.generatedTitle')
                    : t('accessTokensPanel.createTokenModal.newTitle')
            }
            cancelLabel={
                isSuccess
                    ? t('actions.close', { ns: 'common' })
                    : t('actions.cancel', { ns: 'common' })
            }
            icon={IconKey}
            actions={
                !isSuccess ? (
                    <Button
                        type="submit"
                        form="create-token-form"
                        loading={isLoading}
                    >
                        {t('accessTokensPanel.createTokenModal.generate')}
                    </Button>
                ) : undefined
            }
        >
            {!isSuccess ? (
                <form id="create-token-form" onSubmit={handleOnSubmit}>
                    <Stack>
                        <TextInput
                            label={t(
                                'accessTokensPanel.createTokenModal.descriptionLabel',
                            )}
                            disabled={isLoading}
                            placeholder={t(
                                'accessTokensPanel.createTokenModal.descriptionPlaceholder',
                            )}
                            required
                            {...form.getInputProps('description')}
                        />

                        <Select
                            defaultValue={expireOptions[0].value}
                            label={t(
                                'accessTokensPanel.createTokenModal.expiration',
                            )}
                            data={expireOptions}
                            required
                            disabled={isLoading}
                            {...form.getInputProps('expiresAt')}
                        />
                    </Stack>
                </form>
            ) : (
                <Stack gap="md">
                    <TextInput
                        id="invite-link-input"
                        label={t('accessTokensPanel.createTokenModal.token')}
                        readOnly
                        className="sentry-block ph-no-capture"
                        value={data.token}
                        rightSection={
                            <CopyActionIcon
                                value={data.token}
                                tooltipPosition="right"
                            />
                        }
                    />
                    <TextInput
                        id="invite-link-input"
                        label={t(
                            'accessTokensPanel.createTokenModal.cliAuthCode',
                        )}
                        className="sentry-block ph-no-capture"
                        readOnly
                        value={`lightdash login ${health.data?.siteUrl} --token ${data.token}`}
                        rightSection={
                            <CopyActionIcon
                                value={`lightdash login ${health.data?.siteUrl} --token ${data.token}`}
                                tooltipPosition="right"
                            />
                        }
                    />
                    <Callout variant="info">
                        {data.expiresAt &&
                            `${t(
                                'accessTokensPanel.createTokenModal.expiresOn',
                                {
                                    date: formatTimestamp(data.expiresAt),
                                },
                            )} `}
                        {t('accessTokensPanel.createTokenModal.copyWarning')}
                    </Callout>
                </Stack>
            )}
        </MantineModal>
    );
};
