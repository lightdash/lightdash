import {
    AgentCapability,
    FeatureFlags,
    ProjectMemberRole,
} from '@lightdash/common';
import fetch from 'node-fetch';
import { randomUUID } from 'node:crypto';
import {
    createMigratedDatabase,
    type MigratedDatabase,
} from '../../../testing/migratedDatabase';
import {
    connectionFixture,
    matrix,
    seedConnectionClient,
} from './agentConnectionFixture';
import {
    enableConnectionFlag,
    forEachInOrder,
    httpRequest,
    sessionCookie,
    startConnectionHttpServer,
} from './agentConnectionHttpHarness';

let migrated: MigratedDatabase;
let server: Awaited<ReturnType<typeof startConnectionHttpServer>>;
beforeAll(async () => {
    migrated = await createMigratedDatabase();
    await seedConnectionClient(migrated.database);
    server = await startConnectionHttpServer(migrated.database);
});
afterAll(async () => {
    await server?.close();
    await migrated?.destroy();
});
const path = '/api/v2/user/agent-connections';

it.each(['session', 'pat'] as const)(
    'lists, inspects and revokes owned connections over registered HTTP routes with %s',
    async (kind) => {
        const f = await connectionFixture(migrated.database);
        await enableConnectionFlag(f.database, f.organizationUuid);
        const secondProject = await f.createProject();
        const active = await f.createConnection(
            [AgentCapability.ReadDiscover],
            [f.projectUuid, secondProject],
        );
        const second = await f.createConnection();
        const expired = await f.createConnection();
        const revoked = await f.createConnection();
        await f.database.raw(
            "UPDATE agent_connection_grants SET approved_at = clock_timestamp() - interval '2 minutes', expires_at = clock_timestamp() - interval '1 minute' WHERE agent_connection_grant_uuid = ?",
            [expired.grant.grantUuid],
        );
        await f.grants.revoke({
            grantUuid: revoked.grant.grantUuid,
            organizationUuid: f.organizationUuid,
            revokedByUserUuid: f.userUuid,
            reason: 'test',
        });
        const stranger = await connectionFixture(
            migrated.database,
            f.organizationUuid,
        );
        const otherConnection = await stranger.createConnection();
        const cookie = await sessionCookie(
            f.database,
            f.userUuid,
            f.organizationUuid,
        );
        const pat = await server.models.getPersonalAccessTokenModel().create(
            { userId: f.user.user_id },
            {
                description: 'Lifecycle test',
                expiresAt: null,
                autoGenerated: false,
            },
        );
        const headers: Record<string, string> =
            kind === 'session'
                ? { cookie }
                : { authorization: `ApiKey ${pat.token}` };
        const request = (suffix = '', method = 'GET') =>
            httpRequest(server.base, `${path}${suffix}`, headers, method);
        const list = await request();
        expect(list.status).toBe(200);
        const expectedRecord = async (
            connection: typeof active,
            state: string,
            projects = [f.projectUuid],
        ) => {
            const grant = (await f.grants.find(connection.grant.grantUuid))!;
            return {
                grantUuid: grant.grantUuid,
                name: 'Contract CLI',
                clientId: 'lightdash-cli',
                limitsStatus: 'ok',
                approvedProjects: projects.map((projectUuid) => ({
                    projectUuid,
                    name: 'Contract project',
                    approvedCapabilities: [AgentCapability.ReadDiscover],
                })),
                approvedAt: grant.approvedAt.toISOString(),
                expiresAt: grant.expiresAt.toISOString(),
                lastUsedAt: grant.lastUsedAt?.toISOString() ?? null,
                status: state,
                revokedAt: grant.revokedAt?.toISOString() ?? null,
            };
        };
        const records = await Promise.all([
            expectedRecord(active, 'active', [f.projectUuid, secondProject]),
            expectedRecord(second, 'active'),
            expectedRecord(expired, 'expired'),
            expectedRecord(revoked, 'revoked'),
        ]);
        const byId = (a: { grantUuid: string }, b: { grantUuid: string }) =>
            a.grantUuid.localeCompare(b.grantUuid);
        expect({
            ...list.body,
            results: [...list.body.results].sort(byId),
        }).toEqual({ status: 'ok', results: records.sort(byId) });
        expect(list.body.results).toHaveLength(4);
        expect(
            list.body.results
                .map((record: { grantUuid: string }) => record.grantUuid)
                .sort(),
        ).toEqual(
            [active, second, expired, revoked]
                .map((c) => c.grant.grantUuid)
                .sort(),
        );
        const status = await request(`/${active.grant.grantUuid}/status`);
        expect(status.status).toBe(200);
        expect(status.body).toEqual({
            status: 'ok',
            results: {
                ...records.find(
                    (record) => record.grantUuid === active.grant.grantUuid,
                ),
                effectiveProjects: [f.projectUuid, secondProject].map(
                    (projectUuid) => ({
                        projectUuid,
                        capabilities: [
                            {
                                capability: AgentCapability.ReadDiscover,
                                allowed: true,
                                reason: null,
                            },
                        ],
                    }),
                ),
            },
        });
        expect(status.body.results.effectiveProjects).toEqual(
            [f.projectUuid, secondProject].map((projectUuid) => ({
                projectUuid,
                capabilities: [
                    {
                        capability: AgentCapability.ReadDiscover,
                        allowed: true,
                        reason: null,
                    },
                ],
            })),
        );
        await forEachInOrder(
            [
                [expired, 'expired'],
                [revoked, 'revoked'],
            ] as const,
            async ([connection, state]) => {
                expect(
                    await request(`/${connection.grant.grantUuid}/status`),
                ).toEqual({
                    status: 200,
                    body: {
                        status: 'ok',
                        results: {
                            ...(await expectedRecord(connection, state)),
                            effectiveProjects: [
                                {
                                    projectUuid: f.projectUuid,
                                    capabilities: [
                                        {
                                            capability:
                                                AgentCapability.ReadDiscover,
                                            allowed: false,
                                            reason: state,
                                        },
                                    ],
                                },
                            ],
                        },
                    },
                });
            },
        );
        await forEachInOrder(
            [otherConnection.grant.grantUuid, randomUUID()],
            async (id) => {
                await forEachInOrder(
                    [
                        [`/${id}/status`, 'GET'],
                        [`/${id}`, 'DELETE'],
                    ],
                    async ([suffix, method]) => {
                        expect(await request(suffix, method)).toEqual({
                            status: 404,
                            body: {
                                status: 'error',
                                error: {
                                    statusCode: 404,
                                    name: 'NotFoundError',
                                    message: 'Agent connection not found',
                                    data: {},
                                },
                            },
                        });
                    },
                );
            },
        );
        const validationMessage =
            "Not match in '[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-4[0-9A-Fa-f]{3}-[89ABab][0-9A-Fa-f]{3}-[0-9A-Fa-f]{12}'";
        const malformed = {
            status: 422,
            body: {
                status: 'error',
                error: {
                    statusCode: 422,
                    name: 'ValidateError',
                    message: `grantUuid: ${validationMessage}`,
                    data: {
                        grantUuid: {
                            message: validationMessage,
                            value: 'not-a-uuid',
                        },
                    },
                },
            },
        };
        expect(await request('/not-a-uuid/status')).toEqual(malformed);
        expect(await request('/not-a-uuid', 'DELETE')).toEqual(malformed);
        const deleted = await request(`/${active.grant.grantUuid}`, 'DELETE');
        expect(deleted.status).toBe(200);
        expect(deleted.body).toEqual({
            status: 'ok',
            results: await expectedRecord(active, 'revoked', [
                f.projectUuid,
                secondProject,
            ]),
        });
        expect(await request(`/${active.grant.grantUuid}`, 'DELETE')).toEqual(
            deleted,
        );
        expect(
            await httpRequest(
                server.base,
                `${path}/${active.grant.grantUuid}/status`,
                { authorization: `Bearer ${active.accessToken}` },
            ),
        ).toEqual({ status: 401, body: { error: 'invalid_token' } });
        expect(
            (
                await httpRequest(
                    server.base,
                    `${path}/${second.grant.grantUuid}/status`,
                    { authorization: `Bearer ${second.accessToken}` },
                )
            ).status,
        ).toBe(200);
        const refresh = await fetch(`${server.base}/api/v1/oauth/token`, {
            method: 'POST',
            headers: { 'content-type': 'application/x-www-form-urlencoded' },
            body: new URLSearchParams({
                client_id: 'lightdash-cli',
                grant_type: 'refresh_token',
                refresh_token: active.refreshToken,
                resource: active.grant.resource,
            }).toString(),
        });
        const refreshBody = await refresh.json();
        expect(refresh.status).toBe(401);
        expect(refreshBody).toEqual({
            error: 'invalid_grant',
            error_description: 'Invalid grant: refresh token is invalid',
        });
        expect(
            await stranger.grants.find(otherConnection.grant.grantUuid),
        ).toMatchObject({ revokedAt: null });
        await server.models
            .getFeatureFlagModel()
            .upsertOrganizationOverride(
                FeatureFlags.AgentIdentity,
                f.organizationUuid,
                false,
            );
        const disabledList = await request();
        expect(disabledList.status).toBe(200);
        expect([...disabledList.body.results].sort(byId)).toEqual(
            (
                await Promise.all([
                    expectedRecord(active, 'revoked', [
                        f.projectUuid,
                        secondProject,
                    ]),
                    expectedRecord(second, 'active'),
                    expectedRecord(expired, 'expired'),
                    expectedRecord(revoked, 'revoked'),
                ])
            ).sort(byId),
        );
        const disabled = await request(`/${second.grant.grantUuid}/status`);
        expect(disabled.status).toBe(200);
        expect(disabled.body).toEqual({
            status: 'ok',
            results: {
                ...(await expectedRecord(second, 'active')),
                effectiveProjects: [
                    {
                        projectUuid: f.projectUuid,
                        capabilities: [
                            {
                                capability: AgentCapability.ReadDiscover,
                                allowed: false,
                                reason: 'agent_identity_disabled',
                            },
                        ],
                    },
                ],
            },
        });
        expect(
            await httpRequest(
                server.base,
                `${path}/${second.grant.grantUuid}/status`,
                { authorization: `Bearer ${second.accessToken}` },
            ),
        ).toEqual({ status: 401, body: { error: 'invalid_token' } });
        const disabledRevoke = await request(
            `/${second.grant.grantUuid}`,
            'DELETE',
        );
        expect(disabledRevoke).toEqual({
            status: 200,
            body: {
                status: 'ok',
                results: await expectedRecord(second, 'revoked'),
            },
        });
        expect(await request(`/${second.grant.grantUuid}`, 'DELETE')).toEqual(
            disabledRevoke,
        );
    },
);

it('a bound bearer cannot list or manage a sibling, but can inspect and revoke its own connection after policy narrowing', async () => {
    const f = await connectionFixture(migrated.database);
    await enableConnectionFlag(f.database, f.organizationUuid);
    const connection = await f.createConnection();
    const sibling = await f.createConnection();
    const headers = { authorization: `Bearer ${connection.accessToken}` };
    const request = (suffix = '', method = 'GET') =>
        httpRequest(server.base, `${path}${suffix}`, headers, method);
    expect(await request()).toEqual({
        status: 403,
        body: {
            status: 'error',
            error: {
                statusCode: 403,
                name: 'ForbiddenError',
                message: "This agent connection can't use this operation.",
                data: {},
            },
        },
    });
    await forEachInOrder(
        [sibling.grant.grantUuid, randomUUID()],
        async (id) => {
            expect(await request(`/${id}/status`)).toEqual({
                status: 404,
                body: {
                    status: 'error',
                    error: {
                        statusCode: 404,
                        name: 'NotFoundError',
                        message: 'Agent connection not found',
                        data: {},
                    },
                },
            });
            expect(await request(`/${id}`, 'DELETE')).toEqual({
                status: 404,
                body: {
                    status: 'error',
                    error: {
                        statusCode: 404,
                        name: 'NotFoundError',
                        message: 'Agent connection not found',
                        data: {},
                    },
                },
            });
        },
    );
    const expectedRecord = async (state: 'active' | 'revoked') => {
        const grant = (await f.grants.find(connection.grant.grantUuid))!;
        return {
            grantUuid: connection.grant.grantUuid,
            name: 'Contract CLI',
            clientId: 'lightdash-cli',
            limitsStatus: 'ok',
            approvedProjects: [
                {
                    projectUuid: f.projectUuid,
                    name: 'Contract project',
                    approvedCapabilities: [AgentCapability.ReadDiscover],
                },
            ],
            approvedAt: grant.approvedAt.toISOString(),
            expiresAt: grant.expiresAt.toISOString(),
            lastUsedAt: grant.lastUsedAt?.toISOString() ?? null,
            status: state,
            revokedAt: grant.revokedAt?.toISOString() ?? null,
        };
    };
    await f.savePolicy({ allowedCapabilities: [] });
    const status = await request(`/${connection.grant.grantUuid}/status`);
    expect(status).toEqual({
        status: 200,
        body: {
            status: 'ok',
            results: {
                ...(await expectedRecord('active')),
                effectiveProjects: [
                    {
                        projectUuid: f.projectUuid,
                        capabilities: [
                            {
                                capability: AgentCapability.ReadDiscover,
                                allowed: false,
                                reason: 'agent_policy',
                            },
                        ],
                    },
                ],
            },
        },
    });
    const revoked = await request(`/${connection.grant.grantUuid}`, 'DELETE');
    expect(revoked).toEqual({
        status: 200,
        body: { status: 'ok', results: await expectedRecord('revoked') },
    });
    expect(await request(`/${connection.grant.grantUuid}/status`)).toEqual({
        status: 401,
        body: { error: 'invalid_token' },
    });
    expect(await f.grants.find(sibling.grant.grantUuid)).toMatchObject({
        revokedAt: null,
    });
});

it.each(['session', 'pat'] as const)(
    'status computes current project, person and policy restrictions for %s',
    async (kind) => {
        const f = await connectionFixture(migrated.database);
        await enableConnectionFlag(f.database, f.organizationUuid);
        const capabilities = [
            AgentCapability.ReadDiscover,
            AgentCapability.DeployUpload,
        ];
        await f
            .database('project_memberships')
            .where('user_id', f.user.user_id)
            .update({ role: ProjectMemberRole.DEVELOPER });
        await f.savePolicy({
            systemRoleMatrix: {
                ...matrix(capabilities),
                developer: capabilities,
            },
        });
        const connection = await f.createConnection(capabilities);
        const cookie = await sessionCookie(
            f.database,
            f.userUuid,
            f.organizationUuid,
        );
        const pat = await server.models.getPersonalAccessTokenModel().create(
            { userId: f.user.user_id },
            {
                description: 'Status test',
                expiresAt: null,
                autoGenerated: false,
            },
        );
        const headers: Record<string, string> =
            kind === 'session'
                ? { cookie }
                : { authorization: `ApiKey ${pat.token}` };
        const request = () =>
            httpRequest(
                server.base,
                `${path}/${connection.grant.grantUuid}/status`,
                headers,
            );
        const original = await request();
        expect(original.status).toBe(200);
        expect(original.body.results.effectiveProjects).toEqual([
            {
                projectUuid: f.projectUuid,
                capabilities: capabilities.map((capability) => ({
                    capability,
                    allowed: true,
                    reason: null,
                })),
            },
        ]);
        await f
            .database('project_memberships')
            .where('user_id', f.user.user_id)
            .update({ role: ProjectMemberRole.VIEWER });
        const lowered = await request();
        expect(lowered).toEqual({
            status: 200,
            body: {
                ...original.body,
                results: {
                    ...original.body.results,
                    effectiveProjects: [
                        {
                            projectUuid: f.projectUuid,
                            capabilities: [
                                {
                                    capability: AgentCapability.ReadDiscover,
                                    allowed: true,
                                    reason: null,
                                },
                                {
                                    capability: AgentCapability.DeployUpload,
                                    allowed: false,
                                    reason: 'person_permission',
                                },
                            ],
                        },
                    ],
                },
            },
        });
        await f.savePolicy({ allowedCapabilities: [] });
        const narrowed = await request();
        expect(narrowed).toEqual({
            status: 200,
            body: {
                ...lowered.body,
                results: {
                    ...lowered.body.results,
                    effectiveProjects: [
                        {
                            projectUuid: f.projectUuid,
                            capabilities: [
                                {
                                    capability: AgentCapability.ReadDiscover,
                                    allowed: false,
                                    reason: 'agent_policy',
                                },
                                {
                                    capability: AgentCapability.DeployUpload,
                                    allowed: false,
                                    reason: 'person_permission',
                                },
                            ],
                        },
                    ],
                },
            },
        });
        await f.projects.deleteProjectAccess(f.projectUuid, f.userUuid);
        const removed = await request();
        expect(removed).toEqual({
            status: 200,
            body: {
                ...original.body,
                results: {
                    ...original.body.results,
                    approvedProjects: [
                        {
                            projectUuid: f.projectUuid,
                            name: null,
                            approvedCapabilities: capabilities,
                        },
                    ],
                    effectiveProjects: [
                        {
                            projectUuid: f.projectUuid,
                            capabilities: capabilities.map((capability) => ({
                                capability,
                                allowed: false,
                                reason: 'project_access',
                            })),
                        },
                    ],
                },
            },
        });
    },
);
