import { OrganizationMemberRole } from '@lightdash/common';
import { type Knex } from 'knex';
import { randomUUID } from 'node:crypto';
import { fromApiKey } from '../../../auth/account/account';
import { lightdashConfigMock } from '../../../config/lightdashConfig.mock';
import { PersonalAccessTokenModel } from '../../../models/DashboardModel/PersonalAccessTokenModel';
import { FeatureFlagModel } from '../../../models/FeatureFlagModel/FeatureFlagModel';
import { UserModel } from '../../../models/UserModel';
import { UserService } from '../../../services/UserService';
import {
    createMigratedDatabase,
    type MigratedDatabase,
} from '../../../testing/migratedDatabase';
import { hash } from '../../../utils/hash';
import {
    down,
    up,
} from '../20261125160000_add_cli_oauth_pat_compat_to_personal_access_tokens';

vi.mock('../../../config/lightdashConfig', async () => {
    const { lightdashConfigMock: config } =
        await import('../../../config/lightdashConfig.mock');
    return { lightdashConfig: config };
});

const COLUMN = 'cli_oauth_pat_compat';

const lightdashConfig = {
    ...lightdashConfigMock,
    auth: {
        ...lightdashConfigMock.auth,
        pat: { ...lightdashConfigMock.auth.pat, enabled: true },
    },
};

describe('personal access token CLI mark on the migrated schema', () => {
    let migrated: MigratedDatabase;
    let database: Knex;
    let patModel: PersonalAccessTokenModel;
    let userModel: UserModel;

    beforeAll(async () => {
        vi.stubEnv(
            'LIGHTDASH_SECRET',
            lightdashConfigMock.lightdashSecrets.active,
        );
        migrated = await createMigratedDatabase();
        database = migrated.database;
        patModel = new PersonalAccessTokenModel({ database });
        userModel = new UserModel({
            database,
            lightdashConfig,
            featureFlagModel: new FeatureFlagModel({
                database,
                lightdashConfig,
            }),
        });
    });

    afterAll(async () => {
        vi.unstubAllEnvs();
        await migrated?.destroy();
    });

    const columnInfo = () =>
        database('information_schema.columns')
            .select('data_type', 'is_nullable', 'column_default')
            .where({
                table_name: 'personal_access_tokens',
                column_name: COLUMN,
            })
            .first();

    const createUser = async () => {
        const [organization] = await database('organizations')
            .insert({ organization_name: 'PAT CLI mark' })
            .returning(['organization_id', 'organization_uuid']);
        const [user] = await database('users')
            .insert({
                user_uuid: randomUUID(),
                first_name: 'Pat',
                last_name: 'User',
                is_marketing_opted_in: false,
                is_tracking_anonymized: true,
                is_setup_complete: true,
                is_active: true,
            })
            .returning(['user_id', 'user_uuid']);
        await database('organization_memberships').insert({
            user_id: user.user_id,
            organization_id: organization.organization_id,
            role: OrganizationMemberRole.ADMIN,
        });
        return {
            userId: user.user_id as number,
            userUuid: user.user_uuid as string,
            organizationUuid: organization.organization_uuid as string,
        };
    };

    const tokenData = {
        expiresAt: new Date(Date.now() + 60 * 60 * 1000),
        description: 'token',
        autoGenerated: false,
    };

    it('adds a NOT NULL boolean column that defaults to false', async () => {
        expect(await columnInfo()).toEqual({
            data_type: 'boolean',
            is_nullable: 'NO',
            column_default: 'false',
        });
    });

    it('gives rows inserted without the column the value false', async () => {
        const { userId } = await createUser();
        const [row] = await database('personal_access_tokens')
            .insert({
                created_by_user_id: userId,
                expires_at: null,
                description: 'old release insert',
                token_hash: await hash(`ldpat_${randomUUID()}`),
            })
            .returning('*');
        expect(row[COLUMN]).toBe(false);
    });

    it('writes and reads the mark through the model', async () => {
        const { userId, userUuid } = await createUser();
        const marked = await patModel.create({ userId }, tokenData, {
            cliOAuthPatCompat: true,
        });
        const normal = await patModel.create({ userId }, tokenData);
        expect(marked).not.toHaveProperty('cliOAuthPatCompat');

        const rows = await database('personal_access_tokens')
            .select('personal_access_token_uuid', COLUMN)
            .whereIn('personal_access_token_uuid', [marked.uuid, normal.uuid]);
        expect(
            Object.fromEntries(
                rows.map((row) => [
                    row.personal_access_token_uuid,
                    row[COLUMN],
                ]),
            ),
        ).toEqual({ [marked.uuid]: true, [normal.uuid]: false });

        await expect(
            patModel.getUserToken({ userUuid, tokenUuid: marked.uuid }),
        ).resolves.toMatchObject({ cliOAuthPatCompat: true });
        await expect(
            patModel.getUserToken({ userUuid, tokenUuid: normal.uuid }),
        ).resolves.toMatchObject({ cliOAuthPatCompat: false });
    });

    it.each([true, false])(
        'carries the mark %s from the token row to the account',
        async (cliOAuthPatCompat) => {
            const user = await createUser();
            const { token } = await patModel.create(
                { userId: user.userId },
                tokenData,
                { cliOAuthPatCompat },
            );

            await expect(
                userModel.findSessionUserByPersonalAccessToken(token),
            ).resolves.toMatchObject({ data: { cliOAuthPatCompat } });

            const users = new UserService({
                userModel,
                personalAccessTokenModel: patModel,
            } as unknown as ConstructorParameters<typeof UserService>[0]);
            vi.spyOn(users, 'loginToOrganization').mockResolvedValue({
                organizationUuid: user.organizationUuid,
            } as Awaited<ReturnType<UserService['loginToOrganization']>>);
            const sessionUser = await users.loginWithPersonalAccessToken(token);
            expect(sessionUser.personalAccessToken).toEqual({
                cliOAuthPatCompat,
            });
            expect(
                fromApiKey(sessionUser, `ApiKey ${token}`).authentication,
            ).toEqual({
                type: 'pat',
                source: `ApiKey ${token}`,
                cliOAuthPatCompat,
            });
        },
    );

    it('drops the column on down and adds it back on up', async () => {
        await database.transaction(async (trx) => {
            await down(trx);
        });
        expect(await columnInfo()).toBeUndefined();
        await database.transaction(async (trx) => {
            await up(trx);
        });
        expect(await columnInfo()).toEqual({
            data_type: 'boolean',
            is_nullable: 'NO',
            column_default: 'false',
        });
    });
});
