import { ForbiddenError, LightdashCliVersionHeader } from '@lightdash/common';
import express, {
    type ErrorRequestHandler,
    type Request,
    type RequestHandler,
} from 'express';
import { once } from 'node:events';
import { request as httpRequest } from 'node:http';
import { type AddressInfo } from 'node:net';
import { lightdashConfigMock } from '../../config/lightdashConfig.mock';
import Logger from '../../logging/logger';
import { PersonalAccessTokenService } from '../../services/PersonalAccessTokenService';
import { UserController } from '../userController';
import { setupGrantAuthentication } from './agentConnectionGrants.mock';
import { allowOauthAuthentication, isAuthenticated } from './middlewares';

vi.mock('../../ee/authentication', () => ({
    authenticateServiceAccount: vi.fn(),
}));
vi.mock('../../logging/logger', () => ({
    default: { warn: vi.fn(), error: vi.fn(), info: vi.fn(), child: vi.fn() },
}));

beforeEach(() => vi.clearAllMocks());

it.each([true, false])(
    'logs exactly once before grant or managed-policy refusal, bound %s',
    async (bound) => {
        const fixture = setupGrantAuthentication();
        if (!bound)
            Object.assign(fixture.token, { agentConnectionGrantUuid: null });
        fixture.permissions.loadRequest.mockResolvedValue({
            enforcementMode: 'managed',
        });
        fixture.permissions.assertOperationWithRequest.mockRejectedValue(
            new ForbiddenError('Policy refused'),
        );
        const assertRestOperation = vi.spyOn(
            fixture.service,
            'assertRestOperation',
        );
        const write = vi.fn();
        const pat = new PersonalAccessTokenService({
            lightdashConfig: lightdashConfigMock,
            analytics: { track: vi.fn() },
            personalAccessTokenModel: { create: write },
        } as unknown as ConstructorParameters<
            typeof PersonalAccessTokenService
        >[0]);
        const services = {
            ...fixture.req.services,
            getPersonalAccessTokenService: () => pat,
        } as Request['services'];
        const controller = new UserController(services);
        const create = vi.spyOn(controller, 'createPersonalAccessToken');
        const body = {
            description: 'test',
            autoGenerated: false,
            expiresAt: new Date(Date.now() + 86400000),
        };
        let authenticatedRequest: Request | null = null;
        const app = express();
        app.use((req, _res, next) => {
            req.services = services;
            req.isAuthenticated = (() => false) as Request['isAuthenticated'];
            authenticatedRequest = req;
            next();
        });
        const handler: RequestHandler = (req, res, next) => {
            controller
                .createPersonalAccessToken(req, body)
                .then((result) => res.json(result))
                .catch(next);
        };
        Object.defineProperty(handler, 'name', {
            value: 'UserController_createPersonalAccessToken',
        });
        app.post(
            '/api/v1/user/me/personal-access-tokens',
            allowOauthAuthentication,
            isAuthenticated,
            handler,
        );
        const errors: ErrorRequestHandler = (
            error: unknown,
            _req,
            res,
            _next,
        ) => {
            res.sendStatus(error instanceof ForbiddenError ? 403 : 500);
        };
        app.use(errors);
        const server = app.listen(0, '127.0.0.1');
        try {
            await once(server, 'listening');
            const status = await new Promise<number>((resolve, reject) => {
                const request = httpRequest(
                    {
                        hostname: '127.0.0.1',
                        port: (server.address() as AddressInfo).port,
                        path: '/api/v1/user/me/personal-access-tokens',
                        method: 'POST',
                        headers: {
                            authorization: 'Bearer token',
                            [LightdashCliVersionHeader]:
                                'secret-looking-version',
                            'user-agent': 'cli/3.56.0 (person@example.test)',
                        },
                    },
                    (response) => {
                        response.resume();
                        response.on('end', () =>
                            resolve(response.statusCode ?? 0),
                        );
                    },
                );
                request.on('error', reject);
                request.end();
            });
            expect(status).toBe(403);
            expect(create).not.toHaveBeenCalled();
            expect(write).not.toHaveBeenCalled();
            expect(assertRestOperation).not.toHaveBeenCalled();
            expect(fixture.permissions.loadRequest).not.toHaveBeenCalled();
            expect(Logger.warn).toHaveBeenCalledExactlyOnceWith(
                'oauth_credential_mint_refused',
                {
                    operation: 'createPersonalAccessToken',
                    clientId: fixture.token.client.id,
                    scopes: ['read'],
                    userAgent: 'cli/3.56.0 ([redacted])',
                    cliVersion: null,
                    organizationUuid: fixture.user.organizationUuid,
                },
            );
            expect(authenticatedRequest).not.toBeNull();
            await expect(
                controller.createPersonalAccessToken(
                    authenticatedRequest!,
                    body,
                ),
            ).rejects.toBeInstanceOf(ForbiddenError);
            expect(Logger.warn).toHaveBeenCalledTimes(1);
            expect(write).not.toHaveBeenCalled();
        } finally {
            server.closeAllConnections();
            await new Promise<void>((resolve, reject) => {
                server.close((error) => (error ? reject(error) : resolve()));
            });
            assertRestOperation.mockRestore();
        }
    },
);
