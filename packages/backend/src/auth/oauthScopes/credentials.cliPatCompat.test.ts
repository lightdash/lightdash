import { Ability } from '@casl/ability';
import {
    Account,
    AuthTokenPrefix,
    FeatureFlags,
    ForbiddenError,
    OrganizationMemberRole,
    PossibleAbilities,
    RequestMethod,
} from '@lightdash/common';
import { lightdashConfigMock } from '../../config/lightdashConfig.mock';
import { ServiceAccountService } from '../../ee/services/ServiceAccountService/ServiceAccountService';
import Logger from '../../logging/logger';
import { OAuthService } from '../../services/OAuthService/OAuthService';
import { PersonalAccessTokenService } from '../../services/PersonalAccessTokenService';
import {
    fromApiKey,
    fromOauth,
    fromSession,
    toSessionUser,
} from '../account/account';
import { defaultSessionUser } from '../account/account.mock';
import { grantFixture } from '../agentConnectionGrants/grant.mock';
import { CLI_OAUTH_PAT_COMPAT_UNTIL } from './credentials';

const HOUR_MS = 60 * 60 * 1000;
const DAY_MS = 24 * HOUR_MS;
const NOW = new Date('2026-12-01T12:00:00Z');
const OLD_CLI_USER_AGENT =
    'node-fetch/1.0 (+https://github.com/bitinn/node-fetch)';

const user = {
    ...defaultSessionUser,
    role: OrganizationMemberRole.ADMIN,
    ability: new Ability<PossibleAbilities>([
        { action: 'manage', subject: 'all' },
    ]),
};

const oauthAccount = ({
    clientId = 'lightdash-cli',
    scopes = ['read', 'write'],
    grant = false,
    userAgent = OLD_CLI_USER_AGENT,
}: {
    clientId?: string;
    scopes?: string[];
    grant?: boolean;
    userAgent?: string;
} = {}): ReturnType<typeof fromOauth> => {
    const fixture = grantFixture();
    const account = fromOauth(
        user,
        { accessToken: 'secret', client: { id: clientId }, scope: scopes },
        {
            mode: 'enforce',
            getRequest: () => ({
                method: 'POST',
                routeTemplate: '/me/personal-access-tokens',
            }),
        },
        grant
            ? {
                  grantUuid: fixture.grantUuid,
                  revision: fixture.grantRevision,
                  approvedProjectUuids: fixture.approvedProjectUuids,
                  approvedCapabilities: fixture.approvedCapabilities,
                  expiresAt: fixture.expiresAt,
                  clientId,
                  resource: fixture.resource,
                  resourceConstraints: fixture.resourceConstraints,
                  grantContractVersion: fixture.grantContractVersion,
              }
            : null,
    );
    account.requestContext = { userAgent };
    return account;
};

const build = ({
    strict = false,
    maxExpirationTimeInDays,
}: { strict?: boolean; maxExpirationTimeInDays?: number } = {}) => {
    const lightdashConfig = {
        ...lightdashConfigMock,
        auth: {
            ...lightdashConfigMock.auth,
            pat: { ...lightdashConfigMock.auth.pat, maxExpirationTimeInDays },
        },
    };
    const create = vi.fn(async (_user, data) => ({
        uuid: 'pat-uuid',
        token: 'pat-token',
        ...data,
    }));
    const write = vi.fn().mockRejectedValue(new Error('Mutation reached'));
    const featureFlagModel = {
        get: vi.fn(async ({ featureFlagId }: { featureFlagId: string }) => ({
            id: featureFlagId,
            enabled: strict && featureFlagId === FeatureFlags.AgentIdentity,
        })),
    };
    const analytics = { track: vi.fn() };
    const pat = new PersonalAccessTokenService({
        lightdashConfig,
        analytics,
        personalAccessTokenModel: {
            create,
            rotate: write,
            getUserToken: write,
        },
        featureFlagModel,
    } as unknown as ConstructorParameters<
        typeof PersonalAccessTokenService
    >[0]);
    const serviceAccount = new ServiceAccountService({
        lightdashConfig,
        analytics,
        serviceAccountModel: { create: write, rotate: write },
    } as unknown as ConstructorParameters<typeof ServiceAccountService>[0]);
    const oauth = new OAuthService({
        lightdashConfig,
        oauthModel: { createClient: write },
    } as unknown as ConstructorParameters<typeof OAuthService>[0]);
    return { pat, serviceAccount, oauth, create, write, featureFlagModel };
};

const createPat = (
    pat: PersonalAccessTokenService,
    account: Account,
    expiresAt: Date | null,
) =>
    pat.createPersonalAccessToken(
        account,
        {
            expiresAt,
            description: 'Generated by OAuth on 2026-12-01',
            autoGenerated: true,
        },
        RequestMethod.UNKNOWN,
    );

const createdExpiry = (create: ReturnType<typeof build>['create']) =>
    (create.mock.calls[0][1] as { expiresAt: Date }).expiresAt.getTime();

describe('CLI browser-login personal access token exception', () => {
    beforeEach(() => {
        vi.useFakeTimers({ toFake: ['Date'] });
        vi.setSystemTime(NOW);
        vi.spyOn(Logger, 'warn').mockImplementation(() => Logger);
    });
    afterEach(() => {
        vi.useRealTimers();
        vi.restoreAllMocks();
    });

    it.each([
        ['absent', null, NOW.getTime() + 8 * HOUR_MS],
        [
            'later than 8 hours',
            new Date(NOW.getTime() + 8 * DAY_MS),
            NOW.getTime() + 8 * HOUR_MS,
        ],
        [
            'earlier than 8 hours',
            new Date(NOW.getTime() + HOUR_MS),
            NOW.getTime() + HOUR_MS,
        ],
    ])(
        'creates a capped token when expiresAt is %s',
        async (_name, expiresAt, expected) => {
            const { pat, create } = build();
            await expect(
                createPat(pat, oauthAccount(), expiresAt),
            ).resolves.toMatchObject({ token: 'pat-token' });
            expect(createdExpiry(create)).toBe(expected);
            expect(Logger.warn).toHaveBeenCalledExactlyOnceWith(
                'oauth_cli_pat_compat_used',
                {
                    clientId: 'lightdash-cli',
                    userUuid: user.userUuid,
                    organizationUuid: user.organizationUuid,
                    expiresAt: new Date(expected).toISOString(),
                    cliVersion: null,
                },
            );
        },
    );

    it('creates the token the 3.87.0 CLI requests and reads a CLI user agent', async () => {
        const { pat, create } = build();
        const account = oauthAccount({ userAgent: 'lightdash-cli/3.87.0' });
        await createPat(pat, account, new Date(NOW.getTime() + 8 * HOUR_MS));
        expect(createdExpiry(create)).toBe(NOW.getTime() + 8 * HOUR_MS);
        expect(Logger.warn).toHaveBeenCalledWith(
            'oauth_cli_pat_compat_used',
            expect.objectContaining({ cliVersion: '3.87.0' }),
        );
    });

    it('keeps the 8-hour cap under a longer instance maximum', async () => {
        const { pat, create } = build({ maxExpirationTimeInDays: 1 });
        await createPat(pat, oauthAccount(), null);
        expect(createdExpiry(create)).toBe(NOW.getTime() + 8 * HOUR_MS);
    });

    it('still refuses an expiry in the past', async () => {
        const { pat, create } = build();
        await expect(
            createPat(pat, oauthAccount(), new Date(NOW.getTime() - DAY_MS)),
        ).rejects.toThrow('Expire time must be in the future');
        expect(create).not.toHaveBeenCalled();
    });

    const expectRefused = async (
        call: Promise<unknown>,
        written: ReturnType<typeof vi.fn>,
        operation: string,
    ) => {
        await expect(call).rejects.toBeInstanceOf(ForbiddenError);
        expect(written).not.toHaveBeenCalled();
        expect(Logger.warn).toHaveBeenCalledExactlyOnceWith(
            'oauth_credential_mint_refused',
            expect.objectContaining({ operation }),
        );
        expect(Logger.warn).not.toHaveBeenCalledWith(
            'oauth_cli_pat_compat_used',
            expect.anything(),
        );
    };

    it.each([
        [
            'a self-registered client named Lightdash CLI',
            { clientId: 'mcp-lightdashcli' },
        ],
        ['a URL client id', { clientId: 'https://example.test/lightdash-cli' }],
        ['the CLI client with read only', { scopes: ['read'] }],
        ['the CLI client with mcp:write only', { scopes: ['mcp:write'] }],
        ['the CLI client with a connection grant', { grant: true }],
    ])('refuses personal access token creation for %s', async (_name, opts) => {
        const { pat, create } = build();
        await expectRefused(
            createPat(pat, oauthAccount(opts), null),
            create,
            'createPersonalAccessToken',
        );
    });

    it('refuses personal access token creation in strict mode', async () => {
        const { pat, create, featureFlagModel } = build({ strict: true });
        await expectRefused(
            createPat(pat, oauthAccount(), null),
            create,
            'createPersonalAccessToken',
        );
        expect(featureFlagModel.get).toHaveBeenCalledWith({
            featureFlagId: FeatureFlags.AgentIdentity,
            user: {
                userUuid: user.userUuid,
                organizationUuid: user.organizationUuid,
            },
        });
    });

    it.each([
        CLI_OAUTH_PAT_COMPAT_UNTIL,
        new Date(CLI_OAUTH_PAT_COMPAT_UNTIL.getTime() + DAY_MS),
    ])('refuses personal access token creation at %s', async (now) => {
        vi.setSystemTime(now);
        const { pat, create, featureFlagModel } = build();
        await expectRefused(
            createPat(pat, oauthAccount(), null),
            create,
            'createPersonalAccessToken',
        );
        expect(featureFlagModel.get).not.toHaveBeenCalled();
    });

    it('allows creation one millisecond before the end date', async () => {
        vi.setSystemTime(CLI_OAUTH_PAT_COMPAT_UNTIL.getTime() - 1);
        const { pat, create } = build();
        await createPat(pat, oauthAccount(), null);
        expect(create).toHaveBeenCalledOnce();
    });

    it('refuses personal access token rotation from the CLI client', async () => {
        const { pat, write } = build();
        await expectRefused(
            pat.rotatePersonalAccessToken(oauthAccount(), 'token', {
                expiresAt: new Date(NOW.getTime() + DAY_MS),
            }),
            write,
            'rotatePersonalAccessToken',
        );
    });

    it.each([
        [
            'createServiceAccount',
            ({ serviceAccount }: ReturnType<typeof build>) =>
                serviceAccount.create({
                    user: toSessionUser(oauthAccount()),
                    tokenDetails: {
                        organizationUuid: user.organizationUuid!,
                        description: 'service',
                        expiresAt: new Date(NOW.getTime() + DAY_MS),
                        scopes: [],
                    },
                    prefix: AuthTokenPrefix.SERVICE_ACCOUNT,
                }),
        ],
        [
            'createScimToken',
            ({ serviceAccount }: ReturnType<typeof build>) =>
                serviceAccount.create({
                    user: toSessionUser(oauthAccount()),
                    tokenDetails: {
                        organizationUuid: user.organizationUuid!,
                        description: 'scim',
                        expiresAt: new Date(NOW.getTime() + DAY_MS),
                        scopes: [],
                    },
                    prefix: AuthTokenPrefix.SCIM,
                }),
        ],
        [
            'createOAuthClient',
            ({ oauth }: ReturnType<typeof build>) =>
                oauth.createAdminClient(oauthAccount(), {
                    clientName: 'Lightdash CLI',
                    redirectUris: ['https://example.test/callback'],
                }),
        ],
    ])('refuses %s from the CLI client', async (operation, call) => {
        const services = build();
        await expectRefused(call(services), services.write, operation);
    });

    it.each([
        ['session', () => fromSession(user, 'cookie')],
        ['personal access token', () => fromApiKey(user, 'secret')],
    ])('leaves %s authentication unchanged', async (_name, account) => {
        const { pat, create, featureFlagModel } = build();
        const expiresAt = new Date(NOW.getTime() + 365 * DAY_MS);
        await createPat(pat, account(), expiresAt);
        expect(createdExpiry(create)).toBe(expiresAt.getTime());
        expect(featureFlagModel.get).not.toHaveBeenCalled();
        expect(Logger.warn).not.toHaveBeenCalled();
    });
});
