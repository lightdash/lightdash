type JwtOptions = {
    userEmail?: string;
    userExternalId?: string | null;
    canExportCsv?: boolean;
    canExportImages?: boolean;
    canExportPagePdf?: boolean;
    canDateZoom?: boolean;
    canExplore?: boolean;
};

// Logs in as admin, mints an embed JWT for the project's first dashboard, then logs out again.
export const getJwtToken = async (
    api: APIRequestContext,
    projectUuid: string,
    options: JwtOptions = {},
): Promise<string> => {
    const {
        userEmail = 'test@example.com',
        userExternalId = 'test-user-123',
        canExportCsv = false,
        canExportImages = false,
        canExportPagePdf = false,
        canDateZoom = false,
        canExplore = false,
    } = options;

    await loginAs(api, SEED_USERS.admin);

    const dashboardsResponse = await api.get(
        `/api/v1/projects/${projectUuid}/dashboards`,
    );
    expect(dashboardsResponse.status()).toBe(200);
    const dashboards = await json<DashboardBasicDetails[]>(dashboardsResponse);
    expect(dashboards.length).toBeGreaterThan(0);
    const dashboardUuid = dashboards[0].uuid;

    const configResponse = await api.get(`/api/v1/embed/${projectUuid}/config`);
    expect(configResponse.status()).toBe(200);

    const jwtData: CreateEmbedJwt = {
        content: {
            type: 'dashboard',
            projectUuid,
            dashboardUuid,
            canExportCsv,
            canExportImages,
            canExportPagePdf,
            canDateZoom,
            canExplore,
        },
        userAttributes: {
            email: userEmail,
            externalId: userExternalId || '',
        },
        user: {
            email: userEmail,
            externalId: userExternalId || undefined,
        },
        expiresIn: '1h',
    };

    const embedUrlResponse = await api.post(
        `/api/v1/embed/${projectUuid}/get-embed-url`,
        { data: jwtData },
    );
    expect(embedUrlResponse.status()).toBe(200);
    const { url } = await json<{ url: string }>(embedUrlResponse);
    await logout(api);
    return url.split('#')[1];
};

export type ResultRow = Record<
    string,
    { value: { raw: unknown; formatted: string } }
>;

type QueryResults = { status: string; rows: ResultRow[]; error?: string };

// Runs an async metric query through the v2 API and polls until its rows are ready.
export const runMetricQuery = async (
    api: Pick<APIRequestContext, 'get' | 'post'>,
    projectUuid: string,
    query: Record<string, unknown>,
): Promise<ResultRow[]> => {
    const response = await api.post(
        `/api/v2/projects/${projectUuid}/query/metric-query`,
        { data: { context: 'exploreView', query } },
    );
    expect(response.status()).toBe(200);
    const { queryUuid } = await json<{ queryUuid: string }>(response);
    for (;;) {
        const results = await json<QueryResults>(
            await api.get(`/api/v2/projects/${projectUuid}/query/${queryUuid}`),
        );
        if (results.error) throw new Error(`Query failed: ${results.error}`);
        if (results.status === 'ready') return results.rows;
        await new Promise((resolve) => {
            setTimeout(resolve, 200);
        });
    }
};

export const getRawValue = (row: ResultRow, fieldId: string): unknown =>
    row[fieldId].value.raw;
