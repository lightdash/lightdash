export type ProjectPermission = { role: string; projectUuid: string };

// Creates a fresh user with the given org role and project roles, logs in as them and returns their email.
export const loginWithPermissions = async (
    api: APIRequestContext,
    orgRole: string,
    projectPermissions: ProjectPermission[],
): Promise<string> => {
    await loginAs(api, SEED_USERS.admin);
    const email = `demo+${orgRole}-${Date.now()}@lightdash.com`;
    const inviteCode = await invite(api, email, orgRole);
    for (const permission of projectPermissions) {
        await addProjectPermission(
            api,
            email,
            permission.role,
            permission.projectUuid,
        );
    }
    await registerWithCode(api, inviteCode);
    await verifyEmail(api);
    return email;
};

