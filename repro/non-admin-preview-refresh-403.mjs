import { randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const BASE_URL = process.env.LD_URL?.replace(/\/$/, '');
const ADMIN_JAR = process.env.LD_ADMIN_COOKIE_JAR;
const OUT = process.env.OUT ?? 'results.json';
const CLI_VERSION = process.env.LD_CLI_VERSION ?? '3.261.1';
const RUN = process.env.RUN_ID ?? randomBytes(3).toString('hex');

if (!BASE_URL || !ADMIN_JAR) {
    console.error('Set LD_URL and LD_ADMIN_COOKIE_JAR');
    process.exit(2);
}

const cookieHeaderFromJar = (path) =>
    readFileSync(path, 'utf8')
        .split('\n')
        .map((line) => line.replace(/^#HttpOnly_/, ''))
        .filter((line) => line && !line.startsWith('#'))
        .map((line) => line.split('\t'))
        .filter((parts) => parts.length >= 7)
        .map((parts) => `${parts[5]}=${parts[6]}`)
        .join('; ');

const cookieHeaderFromResponse = (response) =>
    response.headers
        .getSetCookie()
        .map((cookie) => cookie.split(';')[0])
        .join('; ');

const sessionAuth = (cookie) => ({ Cookie: cookie });
const cliAuth = (token) => ({
    Authorization: `ApiKey ${token}`,
    'Lightdash-Request-Method': 'CLI',
    'Lightdash-CLI-Version': CLI_VERSION,
});

const request = async (auth, method, path, body) => {
    const response = await fetch(`${BASE_URL}${path}`, {
        method,
        headers: { 'Content-Type': 'application/json', ...auth },
        body: body === undefined ? undefined : JSON.stringify(body),
    });
    const text = await response.text();
    let json;
    try {
        json = JSON.parse(text);
    } catch {
        json = undefined;
    }
    return { status: response.status, json, text, response };
};

const must = (result, label) => {
    if (result.status >= 300) {
        throw new Error(
            `${label} failed: HTTP ${result.status} ${result.text.slice(0, 300)}`,
        );
    }
    return result.json?.results;
};

const messageOf = (result) =>
    result.json?.error?.message ??
    (result.status < 300 ? 'ok' : result.text.slice(0, 200));

const admin = sessionAuth(cookieHeaderFromJar(ADMIN_JAR));
const results = { run: RUN, baseUrl: BASE_URL, setup: [], scenarios: [] };

const me = must(await request(admin, 'GET', '/api/v1/user'), 'admin user');
const projects = must(
    await request(admin, 'GET', '/api/v1/org/projects'),
    'list projects',
);
const upstream = projects.find((project) => project.type === 'DEFAULT');
results.setup.push({
    adminRole: me.role,
    organizationUuid: me.organizationUuid,
    upstreamProjectUuid: upstream.projectUuid,
    upstreamName: upstream.name,
});

const createUser = async (key, orgRole) => {
    const email = `repro-${RUN}-${key}@example.com`;
    const invite = must(
        await request(admin, 'POST', '/api/v1/invite-links', {
            email,
            role: orgRole,
            expiresAt: new Date(Date.now() + 86400000).toISOString(),
        }),
        `invite ${key}`,
    );
    const password = `Rp1-${randomBytes(12).toString('hex')}`;
    const registered = await request(sessionAuth(''), 'POST', '/api/v1/user', {
        inviteCode: invite.inviteCode,
        firstName: 'Repro',
        lastName: key,
        password,
    });
    const user = must(registered, `register ${key}`);
    const cookie = cookieHeaderFromResponse(registered.response);
    const pat = must(
        await request(
            sessionAuth(cookie),
            'POST',
            '/api/v1/user/me/personal-access-tokens',
            {
                description: `repro ${RUN} ${key}`,
                expiresAt: new Date(Date.now() + 86400000).toISOString(),
                autoGenerated: false,
            },
        ),
        `pat ${key}`,
    );
    results.setup.push({ user: key, email, orgRole, userUuid: user.userUuid });
    return {
        key,
        email,
        orgRole,
        userUuid: user.userUuid,
        cookie,
        cli: cliAuth(pat.token),
    };
};

const grantProjectRole = async (user, role) => {
    const result = await request(
        admin,
        'POST',
        `/api/v1/projects/${upstream.projectUuid}/access`,
        { email: user.email, role, sendEmail: false },
    );
    results.setup.push({
        user: user.key,
        upstreamProjectRole: role,
        status: result.status,
        message: messageOf(result),
    });
};

const grantCustomProjectRole = async (user) => {
    const created = await request(
        admin,
        'POST',
        `/api/v2/orgs/${me.organizationUuid}/roles`,
        {
            name: `repro-${RUN}-preview-self`,
            description: 'Repro: preview creation plus update:Project@self only',
            scopes: [
                'view:Project',
                'create:Project@preview',
                'update:Project@self',
                'delete:Project@self',
                'manage:CompileProject',
                'manage:DeployProject@self',
                'create:Job',
                'create:Job@self',
                'view:JobStatus',
            ],
        },
    );
    results.setup.push({
        user: user.key,
        customRole: 'create',
        status: created.status,
        message: messageOf(created),
    });
    if (created.status >= 300) return false;
    const roleId = created.json.results.roleUuid;
    const assigned = await request(
        admin,
        'POST',
        `/api/v2/projects/${upstream.projectUuid}/roles/assignments/user/${user.userUuid}`,
        { roleId, sendEmail: false },
    );
    results.setup.push({
        user: user.key,
        customRole: 'assign',
        roleId,
        status: assigned.status,
        message: messageOf(assigned),
    });
    return assigned.status < 300;
};

const createPreview = async (actor, label) => {
    const body = {
        name: `repro ${RUN} ${label}`,
        type: 'PREVIEW',
        copyWarehouseConnectionFromUpstreamProject: true,
        dbtConnection: { type: 'none' },
        upstreamProjectUuid: upstream.projectUuid,
        dbtVersion: upstream.dbtVersion,
        copyContent: false,
        asyncCopyContent: false,
    };
    const result = await request(
        actor.cli,
        'POST',
        '/api/v1/org/projects',
        body,
    );
    results.scenarios.push({
        scenario: `create:${label}`,
        actor: actor.key,
        actorRole: actor.role,
        createdBy: actor.key,
        endpoint: 'POST /api/v1/org/projects',
        status: result.status,
        message: messageOf(result),
    });
    return result.status < 300
        ? result.json.results.project?.projectUuid ??
              result.json.results.projectUuid
        : undefined;
};

const refreshAsCli = async (scenario, actor, previewUuid, createdBy) => {
    const expiration = await request(
        actor.cli,
        'PATCH',
        `/api/v1/projects/${previewUuid}/preview-expiration`,
        { expiresInHours: undefined },
    );
    results.scenarios.push({
        scenario,
        actor: actor.key,
        actorRole: actor.role,
        createdBy,
        previewUuid,
        endpoint: 'PATCH /api/v1/projects/{uuid}/preview-expiration',
        status: expiration.status,
        message: messageOf(expiration),
    });

    const project = await request(
        actor.cli,
        'GET',
        `/api/v1/projects/${previewUuid}`,
    );
    const source = project.status < 300 ? project.json.results : undefined;
    const fallback = source ?? (
        await request(admin, 'GET', `/api/v1/projects/${previewUuid}`)
    ).json.results;
    const updateBody = {
        name: fallback.name,
        dbtConnection: fallback.dbtConnection,
        dbtVersion: fallback.dbtVersion,
        warehouseConnection: fallback.warehouseConnection,
    };
    const update = await request(
        actor.cli,
        'PATCH',
        `/api/v1/projects/${previewUuid}`,
        updateBody,
    );
    results.scenarios.push({
        scenario,
        actor: actor.key,
        actorRole: actor.role,
        createdBy,
        previewUuid,
        endpoint: 'PATCH /api/v1/projects/{uuid}',
        status: update.status,
        message: messageOf(update),
        getProjectStatus: project.status,
    });
};

const adminPat = must(
    await request(admin, 'POST', '/api/v1/user/me/personal-access-tokens', {
        description: `repro ${RUN} admin`,
        expiresAt: new Date(Date.now() + 86400000).toISOString(),
        autoGenerated: false,
    }),
    'admin pat',
);
const seedAdmin = {
    key: 'seed-admin',
    role: 'org admin',
    cli: cliAuth(adminPat.token),
};

const projectDev = await createUser('projdev', 'member');
projectDev.role = 'org member + upstream project developer';
await grantProjectRole(projectDev, 'developer');

const projectDev2 = await createUser('projdev2', 'member');
projectDev2.role = 'org member + upstream project developer (non-creator)';
await grantProjectRole(projectDev2, 'developer');

const orgDev = await createUser('orgdev', 'developer');
orgDev.role = 'org developer, no project role';

const orgMember = await createUser('member', 'member');
orgMember.role = 'org member, no project role (non-creator)';

const selfScope = await createUser('selfscope', 'member');
selfScope.role =
    'org member + upstream custom role (create:Project@preview, update:Project@self, no update:Project)';
const hasSelfScope = await grantCustomProjectRole(selfScope);

const projectDevPreview = await createPreview(projectDev, 'projdev');
if (projectDevPreview) {
    await refreshAsCli('b:creator', projectDev, projectDevPreview, 'projdev');
    await refreshAsCli(
        'c:non-creator-member',
        orgMember,
        projectDevPreview,
        'projdev',
    );
    await refreshAsCli(
        'c:non-creator-projdev2',
        projectDev2,
        projectDevPreview,
        'projdev',
    );
    await refreshAsCli(
        'd:admin-on-nonadmin-preview',
        seedAdmin,
        projectDevPreview,
        'projdev',
    );
}

const orgDevPreview = await createPreview(orgDev, 'orgdev');
if (orgDevPreview) {
    await refreshAsCli('b:creator', orgDev, orgDevPreview, 'orgdev');
}

const adminPreview = await createPreview(seedAdmin, 'admin');
if (adminPreview) {
    await refreshAsCli('d:admin-creator', seedAdmin, adminPreview, 'seed-admin');
}

if (hasSelfScope) {
    const selfScopePreview = await createPreview(selfScope, 'selfscope');
    if (selfScopePreview) {
        await refreshAsCli(
            'e:creator-self-scope',
            selfScope,
            selfScopePreview,
            'selfscope',
        );
    }
}

writeFileSync(OUT, `${JSON.stringify(results, null, 2)}\n`);
for (const row of results.scenarios) {
    console.log(
        [row.scenario, row.actor, row.createdBy, row.endpoint, row.status, row.message].join(' | '),
    );
}
