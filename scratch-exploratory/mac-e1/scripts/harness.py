from fixtures import ROOT, WORK, source, resources

BASE = 'http://127.0.0.1:18981'
EVIDENCE = WORK / 'evidence.jsonl'


def clean(value):
    text = json.dumps(value, default=str)
    for key in ['LIGHTDASH_SECRET', 'PGPASSWORD', 'S3_SECRET_KEY', 'LOCAL_API_KEY']:
        if os.environ.get(key):
            text = text.replace(os.environ[key], '<local-secret>')
    text = text.replace(str(ROOT), '$WORKTREE')
    text = re.sub(r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}', '<local-id>', text, flags=re.I)
    return json.loads(text)


def record(name, observed):
    entry = clean({'scenario': name, 'commit': subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True).strip(), 'observed': observed})
    with EVIDENCE.open('a') as file:
        file.write(json.dumps(entry) + '\n')
    print(json.dumps(entry)[:1200], flush=True)


def control(data):
    command = ['pnpm', '-F', 'backend', 'exec', 'tsx', 'src/scripts/thunder-expl-e1/control.ts']
    result = subprocess.run(command, input=json.dumps(data), text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(clean({'controlError': result.stderr, 'stdout': result.stdout}))
    return json.loads(result.stdout.strip().splitlines()[-1])


class Api:
    def __init__(self):
        self.jar = http.cookiejar.CookieJar()
        self.opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(self.jar))
        self.trace = []

    def request(self, method, path, body=None):
        headers = {'Content-Type': 'application/json'}
        if os.environ.get('LOCAL_API_KEY'):
            headers['Authorization'] = 'ApiKey ' + os.environ['LOCAL_API_KEY']
        req = urllib.request.Request(BASE + path, data=json.dumps(body).encode() if body is not None else None,
                                     method=method, headers=headers)
        try:
            response = self.opener.open(req, timeout=420)
        except urllib.error.HTTPError as error:
            response = error
        text = response.read().decode()
        try:
            data = json.loads(text)
        except ValueError:
            data = {'raw': text[:400]}
        self.trace.append({'method': method, 'path': path, 'status': response.status})
        return response.status, data

    def ok(self, method, path, body=None):
        status, data = self.request(method, path, body)
        if status >= 400:
            raise RuntimeError(clean({'path': path, 'status': status, 'data': data}))
        return data.get('results')

    def project(self, name):
        projects = self.ok('GET', '/api/v1/org/projects')
        return next((project for project in projects if project['name'] == name), None)

    def setup(self):
        if os.environ.get('LOCAL_API_KEY'):
            return
        password = 'T' + os.environ['LIGHTDASH_SECRET'][:16] + '1!'
        user = {'email': 'exploratory@example.test', 'password': password,
                'firstName': 'Local', 'lastName': 'Tester'}
        status, data = self.request('POST', '/api/v1/user', user)
        if status >= 400:
            self.ok('POST', '/api/v1/login', {'email': user['email'], 'password': password})
        status, data = self.request('PUT', '/api/v1/org', {'name': 'Synthetic exploratory lab'})
        if status >= 400 and 'already' not in json.dumps(data).lower():
            raise RuntimeError(clean(data))
        pat = self.ok('POST', '/api/v1/user/me/personal-access-tokens',
                      {'description': 'Temporary local exploratory testing', 'expiresAt': None, 'autoGenerated': False})
        token = pat['token']
        envfile = WORK / '.env'
        with envfile.open('a') as file:
            file.write(f'LOCAL_API_KEY={token}\n')
        os.environ['LOCAL_API_KEY'] = token
        record('setup', {'user': 'local test account', 'organization': 'synthetic lab', 'tokenCreated': True})

    def ensure_project(self, name, sources):
        project = self.project(name)
        if project is None:
            created = self.ok('POST', '/api/v1/org/projects', {
                'name': name, 'type': 'DEFAULT', 'dbtVersion': 'v1.12',
                'dbtConnection': sources[0]['connection'],
                'warehouseConnection': {'type': 'postgres', 'host': '127.0.0.1', 'port': 15981,
                                        'user': 'postgres', 'password': os.environ['PGPASSWORD'],
                                        'dbname': 'warehouse', 'schema': 'public', 'sslmode': 'disable'},
            })
            project = self.project(name)
        project_id = project['projectUuid']
        control({'action': 'sources', 'project': project_id, 'sources': sources})
        return project_id

    def refresh(self, project):
        resources()
        start = time.monotonic()
        status, data = self.request('POST', f'/api/v1/projects/{project}/refresh', {})
        if status >= 400:
            return {'http': status, 'error': data, 'elapsed': round(time.monotonic() - start, 2)}
        result = data.get('results', {})
        job_id = result.get('jobUuid')
        if not job_id:
            return {'http': status, 'response': data}
        deadline = time.monotonic() + 420
        while time.monotonic() < deadline:
            job = self.ok('GET', f'/api/v1/jobs/{job_id}')
            if job.get('jobStatus') not in ['started', 'scheduled', 'STARTED', 'SCHEDULED', 'RUNNING']:
                return {'http': status, 'job': job, 'elapsed': round(time.monotonic() - start, 2),
                        'explores': self.explores(project)}
            time.sleep(0.5)
        raise RuntimeError('Local refresh timed out')

    def explores(self, project):
        status, data = self.request('GET', f'/api/v1/projects/{project}/explores')
        return data.get('results', data)

    def parameters(self, project):
        return self.ok('GET', f'/api/v2/projects/{project}/parameters')

    def set_parameters(self, project, values):
        return self.ok('PUT', f'/api/v2/projects/{project}/parameters', values)


def cli(project, directory, args, label, old=False):
    resources()
    env = os.environ.copy()
    env['HOME'] = str(WORK / 'cli-home')
    Path(env['HOME']).mkdir(exist_ok=True)
    env['LIGHTDASH_API_KEY'] = env['LOCAL_API_KEY']
    env['LIGHTDASH_URL'] = BASE
    env['LIGHTDASH_PROJECT'] = project
    env['DBT_PROFILES_DIR'] = str(directory)
    env['PGDATABASE'] = 'warehouse'
    env['DBT_SEND_ANONYMOUS_USAGE_STATS'] = 'false'
    if old:
        command = ['sfw', 'npx', '--yes', '--prefix', str(WORK / 'old-cli'), '@lightdash/cli@3.19.0', *args]
    else:
        command = ['node', str(ROOT / 'packages/cli/dist/index.js'), *args]
    result = subprocess.run(command, cwd=directory, env=env, text=True, capture_output=True, timeout=300)
    outcome = {'exit': result.returncode, 'stdout': result.stdout, 'stderr': result.stderr, 'args': args}
    record(label, outcome)
    return outcome
