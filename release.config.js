// PROD-8359 kill-switch (see scripts/gen-release-safety.ts). While the marker is
// dark-launched (RELEASE_SAFETY_MARKER_ENABLED !== "true") the generator leaves the
// committed unknown placeholder unchanged, and GitHub asset publication stays off.
const releaseSafetyMarkerEnabled =
    process.env.RELEASE_SAFETY_MARKER_ENABLED === 'true';

module.exports = {
    branches: [
        '+([0-9])?(.{+([0-9]),x}).x',
        'main',
        'next',
        'next-major',
        { name: 'beta', prerelease: true },
        { name: 'alpha', prerelease: true },
    ],
    plugins: [
        '@semantic-release/commit-analyzer',

        '@semantic-release/release-notes-generator',
        [
            '@semantic-release/changelog',
            {
                changelogFile: 'CHANGELOG.md',
            },
        ],

        // Metadata-only version bump for the release cohort: root plus the
        // eight workspace manifests committed by the git plugin's assets list
        // below. pkg set edits package.json files and nothing else — no
        // dependency resolution, no node_modules reification (npm version
        // reified and destroyed pnpm's layout, which is why a repair install
        // used to live here). Other workspace members (formula, test apps,
        // mcp-chart-app) keep their own unrelated versions on purpose.
        [
            '@semantic-release/exec',
            {
                prepareCmd:
                    'pnpm pkg set version=${nextRelease.version} && pnpm --filter backend --filter @lightdash/cli --filter @lightdash/common --filter e2e --filter @lightdash/frontend --filter @lightdash/warehouses --filter @lightdash/query-sdk --filter @lightdash/sdk pkg set version=${nextRelease.version}',
            },
        ],

        // Unmatched pnpm filters exit 0, so a renamed package would silently
        // stop being versioned. Assert every cohort manifest took the bump.
        [
            '@semantic-release/exec',
            {
                prepareCmd:
                    'for f in package.json packages/backend/package.json packages/cli/package.json packages/common/package.json packages/e2e/package.json packages/frontend/package.json packages/warehouses/package.json packages/query-sdk/package.json packages/frontend/sdk/package.json; do grep -q "\\"version\\": \\"${nextRelease.version}\\"" "$f" || { echo "Version not bumped in $f"; exit 1; }; done',
            },
        ],

        [
            '@semantic-release/exec',
            {
                prepareCmd:
                    'pnpm generate-api:backend',
            },
        ],

        [
            '@semantic-release/exec',
            {
                prepareCmd: 'pnpm build-published-packages',
                publishCmd: 'pnpm release-packages',
            },
        ],

        // Generate the release-safety marker (PROD-8359). Runs before the github
        // plugin so the asset exists at publish time.
        //
        // --rest-from-tag diffs the OpenAPI spec of the previous tag against the
        // working-tree one regenerated by the `pnpm generate-api:backend` step
        // above. It is explicit because the PR-time preview has to generate both
        // sides instead, and neither caller should silently get the other's
        // comparison. Without it the REST surface is reported as not checked.
        //
        // --ai-review activates the gated AI rolling-update review (P6). It runs
        // on every migration-bearing release and on flagged REST/MCP breaks; a
        // definitive verdict can clear or confirm the deterministic floor. It is
        // gated on ANTHROPIC_API_KEY in the release job. Any degrade leaves the
        // floor or honest "unknown" verdict intact; it never fails the release.
        [
            '@semantic-release/exec',
            {
                prepareCmd:
                    'pnpm exec tsx scripts/gen-release-safety.ts --version ${nextRelease.version} --previous-version "${lastRelease.version}" --last-tag "${lastRelease.gitTag}" --out release-safety.json --index release-safety-index.json --rest-from-tag --ai-review',
            },
        ],

        [
            '@semantic-release/exec',
            {
                prepareCmd:
                    'pnpm exec tsx scripts/release-safety-schema.test.ts',
            },
        ],

        './scripts/semantic-release-safety-plugin.js',

        [
            '@semantic-release/git',
            {
                assets: [
                    'CHANGELOG.md',
                    'package.json',
                    'packages/backend/package.json',
                    'packages/cli/package.json',
                    'packages/common/package.json',
                    'packages/e2e/package.json',
                    'packages/frontend/package.json',
                    'packages/warehouses/package.json',
                    'packages/query-sdk/package.json',
                    'packages/frontend/sdk/package.json',
                    'packages/backend/src/generated/routes.ts',
                    'packages/backend/src/generated/swagger.json',
                    // PROD-8359: when the marker generator auto-records this
                    // release's expand/contract upgrade floor, the change to this
                    // committed file ships in the release commit so future releases
                    // carry the floor forward. Unchanged (the common case) → no-op.
                    'release-safety.overrides.json',
                    'release-safety.json',
                    'release-safety-index.json',
                ],
                message:
                    'chore(release): ${nextRelease.version} \n\n${nextRelease.notes}',
            },
        ],
        [
            '@semantic-release/github',
            {
                // Attach the marker only when the kill-switch is on (see above).
                assets: releaseSafetyMarkerEnabled
                    ? [
                          {
                              path: 'release-safety.json',
                              label: 'release-safety.json',
                          },
                      ]
                    : [],
            },
        ],
    ],
    tagFormat: '${version}',
};
