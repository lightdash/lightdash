select
    appointment_id,
    episode_id,
    student_id,
    school_id,
    district_id,
    clinician_id,
    scheduled_at,
    cast(scheduled_at as date) as scheduled_on,
    cast(extract(hour from scheduled_at) as integer) as scheduled_hour,
    to_char(scheduled_at, 'FMDay') as scheduled_weekday,
    {{ school_year('scheduled_at') }} as school_year,
    appointment_type,
    program,
    modality,
    status,
    duration_minutes,
    case when status = 'Completed' then duration_minutes / 60.0 else 0 end as hours_delivered,
    is_during_school_day,
    status = 'Completed' as is_completed,
    status = 'No Show' as is_no_show,
    status like 'Cancelled%' as is_cancelled,
    status in ('Completed', 'No Show') as is_kept_or_missed
from {{ ref('stg_appointments') }}
